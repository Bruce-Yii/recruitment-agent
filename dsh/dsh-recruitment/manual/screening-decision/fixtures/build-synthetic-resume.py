def main() -> int:
    if len(sys.argv) < 2:
        print("usage: build-synthetic-resume.py <out-dir> [phone] [email]", file=sys.stderr)
        return 2
    out_dir = Path(sys.argv[1])
    out_dir.mkdir(parents=True, exist_ok=True)
    doc = fitz.open()
    for lines in PAGES:
        page = doc.new_page(width=595, height=842)  # A4
        for text, size, indent, y in lines:
            if text == "":
                continue
            page.insert_text((56 + indent, y), text, fontname="china-s", fontsize=size)
    target = out_dir / OUT_NAME
    doc.save(target, deflate=True, garbage=3)
    doc.close()
    data = target.read_bytes()
    print(f"WROTE {target}")
    print(f"bytes={len(data)} sha256={hashlib.sha256(data).hexdigest()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
